#!/usr/bin/env python3
"""Assemble audit/REPORT.md from _report_head.md, generated tables and _report_tail.md.
Run scripts/findings-index.py first; it writes raw/scorecard.md and raw/findings-all.md."""
import os, re
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rd = lambda p: open(os.path.join(root, p)).read()

def table_after(path, header_prefix, extra=None):
    L = rd(path).split('\n'); i = next(k for k, l in enumerate(L) if l.startswith(header_prefix)); out = []
    for j, l in enumerate(L[i:]):
        if not l.startswith('|'): break
        if extra:
            l = l.rstrip().rstrip('|').rstrip() + (f' | {extra[0]} |' if j == 0 else (' |---|' if j == 1 else f' | {extra[1]} |'))
        out.append(l)
    return '\n'.join(out) + '\n'

free = table_after('notes/E-scalability.md', '| Service / limit |')
load = table_after('notes/E-scalability.md', '| Run |')
routes = table_after('notes/D-rendering.md', '| Route |', ('Measured FPS / TTI / re-renders', 'NOT TESTED (device)'))
doc = rd('_report_head.md') + """
Counts are findings per category (PASS rows have no severity). Generated by `scripts/findings-index.py`.

""" + rd('raw/scorecard.md') + """
## Free-tier limit table (projected at 5,000 DAU)

Source of limits: [02-research.md](02-research.md). Arithmetic: [E-scalability §3](notes/E-scalability.md).

""" + free + """
## Per-screen performance table

From code review ([D-rendering.md](notes/D-rendering.md)). States column: L Loading, E Empty, Er Error, Of Offline, P Permission-denied. FPS, TTI and re-render counts need a device (see Needs Wasif, item 3).
Targets: steady 60 fps (120 on ProMotion) during swipe and scroll, cold start under 2 s on a mid-range Android phone, no JS task over 100 ms ([02-research.md](02-research.md) §d). Android Hermes bundle: 7.24 MB (about 1.9 MB of source is Sentry and about 0.8 MB is PostHog).

""" + routes + """
## Load test results (k6, local Docker)

Thresholds: p95 < 500 ms and errors < 1%. Think time is 1 to 3 s.
- **First real bottleneck:** DB CPU from `search_suggest`, `search_listings` and `get_quad_feed`.
- **Second:** the PostgREST pool of 10 (PGRST003).
- **Third:** `make_offer` lock contention on hot listings.
- **Local artifacts:** the "EOF" failures above about 500 VUs and the WebSocket failures at scale come from the local Kong cap, not hosted behaviour.

Without search and the Quad: 163 rps at p95 18 ms on about one core. The swipe feed alone held p95 8 ms at 394 rps with 1,000 VUs. Projected need at 5k DAU is about 62 rps at peak and 124 at the 2x spike.

""" + load + """
## All findings

PASS rows are left out here; they are in the notes. Sorted by severity within each category.
""" + rd('raw/findings-all.md') + rd('_report_tail.md')
open(os.path.join(root, 'REPORT.md'), 'w').write(doc)
print('REPORT.md', len(doc.split('\n')), 'lines')
